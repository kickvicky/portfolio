import type { NextConfig } from "next";

// Baseline security headers for every route. (No Content-Security-Policy yet: Next's inline scripts and
// Vercel Analytics need a nonce-based setup, which isn't worth the complexity for a static portfolio.)
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  // Nobody can embed the site in an iframe (prevents clickjacking on the contact form).
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  images: {
    remotePatterns: [{ protocol: "https", hostname: "images.unsplash.com" }],
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
